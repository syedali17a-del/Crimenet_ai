"""Realistic-format synthetic source documents for the CrimeNet AI dataset pack.

Every document mirrors the layout of the real Indian police / telecom / banking
artefact it represents, and every fact inside it (names, plates, phone numbers,
timestamps, locations) is taken from the application seed data so the paperwork
and the running application always agree.

NOTHING HERE IS REAL. Each file carries a synthetic-data banner.
"""
from __future__ import annotations

from . import ds_source as S

W = 80
RULE = "-" * W
HEAVY = "=" * W


def banner(kind: str) -> str:
    return "\n".join([
        HEAVY,
        "SYNTHETIC DEMONSTRATION DATA - NOT A REAL {}".format(kind.upper()).center(W),
        "Generated for the CrimeNet AI prototype. No real person, vehicle, account,".center(W),
        "case, police station, bank or telecom operator is represented.".center(W),
        "Not evidence. Not for operational, legal or investigative use.".center(W),
        HEAVY,
        "",
    ])


def footer(doc_ref: str, evidence_id: str, case_id: str) -> str:
    return "\n".join([
        "",
        RULE,
        f" Document reference : {doc_ref}",
        f" Ingested into CrimeNet AI as : {evidence_id}   (Case {case_id})",
        f" Classification : {S.CLASSIFICATION}",
        RULE,
    ])


def kv(label: str, value: str, width: int = 34) -> str:
    return f" {label.ljust(width, '.')} : {value}"


