def chain_of_custody(evidence_id: str) -> tuple[str, str]:
    ev = S.EVIDENCE_BY_ID[evidence_id]
    case_id = ev["case_id"]
    rows = [
        ("1", ev["timestamp"][:10], "Seized / received at Police Station",
         "Station House Officer", "Original retained in Malkhana"),
        ("2", ev["timestamp"][:10], "Copy produced for analysis",
         ev["uploaded_by"], "Working copy created; original untouched"),
        ("3", ev["timestamp"][:10], "Registered in CrimeNet AI",
         ev["uploaded_by"], "SHA-256 computed at registration and sealed in ledger"),
    ]
    if evidence_id == "EV-2042":
        rows.append(("4", "2025-08-19", "Stored object modified OUTSIDE the application",
                     "UNKNOWN", "DELIBERATE DEMONSTRATION - integrity check will report "
                                "INTEGRITY MISMATCH against the registered hash"))
    lines = [
        banner("Chain of Custody Form"),
        "CHAIN OF CUSTODY / EVIDENCE MOVEMENT REGISTER".center(W),
        "",
        RULE,
        kv(" System evidence reference", evidence_id),
        kv(" Case", f"{case_id} - {S.CASE_BY_ID[case_id]['title']}"),
        kv(" Evidence type", ev["evidence_type"]),
        kv(" Source", ev["source"]),
        kv(" Recorded timestamp", ev["timestamp"]),
        kv(" Registered by", ev["uploaded_by"]),
        kv(" Verification status in system", ev.get("verification_status", "UNVERIFIED")),
        RULE,
        "",
        " Sl.  Date         Movement / Action                Custodian        Remarks",
        " " + "-" * 78,
    ]
    for sl, date, action, cust, remark in rows:
        lines.append(f" {sl:<4} {date:<12} {action:<32} {cust:<16}")
        lines.append(f"      Remarks: {remark}")
    lines += [
        "",
        " DECLARATION",
        " The original record has not been modified by the CrimeNet AI platform. The",
        " platform stores an immutable copy, records its SHA-256 digest at the moment of",
        " registration and seals that digest in an append-only hash-chained ledger.",
        footer(f"COC/{evidence_id} (synthetic)", evidence_id, case_id),
    ]
    return f"CHAIN-OF-CUSTODY_{evidence_id}.txt", "\n".join(lines)
